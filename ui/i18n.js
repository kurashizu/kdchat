let LANG = "en";

function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) ?? I18N.en[key] ?? key;
  if (vars && typeof s === "string") s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  return s;
}

// data-i18n -> textContent; data-i18n-title / -placeholder / -aria / -alt -> that attribute
function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((e) => { e.textContent = t(e.dataset.i18n); });
  for (const [attr, prop] of [["data-i18n-title", "title"], ["data-i18n-placeholder", "placeholder"],
                              ["data-i18n-aria", "aria-label"], ["data-i18n-alt", "alt"]]) {
    root.querySelectorAll(`[${attr}]`).forEach((e) => e.setAttribute(prop, t(e.getAttribute(attr))));
  }
}

export type Key = keyof typeof en;
export type Lang = "en" | "zh" | "ja" | "ko";
const DICTS: Record<Lang, Dict> = { en, zh, ja, ko };
export const LANGS: [Lang, string][] = [["en", "English"], ["zh", "中文"], ["ja", "日本語"], ["ko", "한국어"]];
// the html lang attribute: picks the right CJK glyph forms
export const HTML_LANG: Record<Lang, string> = { en: "en", zh: "zh-CN", ja: "ja", ko: "ko" };
// a translation language code -> its html lang (its own glyph forms, not the interface language's)
export const langTag = (code: string) => ({ zh: "zh-CN", zh_hant: "zh-TW", hbs: "sh" })[code] ?? code;
const isLang = (v: unknown): v is Lang => typeof v === "string" && v in DICTS;

function initial(): Lang {
  const q = new URLSearchParams(location.search).get("lang"); // ?lang=zh (a link in the docs)
  if (isLang(q)) return q;
  const saved = store.get<string | null>("lang", null);
  if (isLang(saved)) return saved;
  const nav = (navigator.language || "").toLowerCase().slice(0, 2);
  return isLang(nav) ? nav : "en";
}

export const i18n = $state({ lang: initial() as Lang });

export function setLang(l: Lang) {
  i18n.lang = l;
  store.set("lang", l);
  document.documentElement.lang = HTML_LANG[l];
}
document.documentElement.lang = HTML_LANG[i18n.lang];

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = (DICTS[i18n.lang][key] ?? en[key] ?? key) as string;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

export function colorName(i: number): string {
  const list = (DICTS[i18n.lang].colors ?? en.colors) as string[];
  return list[i] ?? String(i);
}

// an option's display name ("layout.chat"); falls back to the raw value
export function opt(prefix: string, v: string | number): string {
  const k = `${prefix}.${v}` as Key;
  const s = t(k);
  return s === k ? String(v) : s;
}

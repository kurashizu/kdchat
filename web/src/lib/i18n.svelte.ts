export type Key = keyof typeof en;
export type Lang = "en" | "zh";
const DICTS: Record<Lang, Dict> = { en, zh };

function initial(): Lang {
  const q = new URLSearchParams(location.search).get("lang"); // ?lang=zh (a link in the docs)
  if (q === "en" || q === "zh") return q;
  const saved = store.get<string | null>("lang", null);
  if (saved === "en" || saved === "zh") return saved;
  return (navigator.language || "").toLowerCase().startsWith("zh") ? "zh" : "en";
}

export const i18n = $state({ lang: initial() as Lang });

export function setLang(l: Lang) {
  i18n.lang = l;
  store.set("lang", l);
  document.documentElement.lang = l === "zh" ? "zh-CN" : "en";
}
document.documentElement.lang = i18n.lang === "zh" ? "zh-CN" : "en";

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = (DICTS[i18n.lang][key] ?? en[key] ?? key) as string;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

export function colorName(i: number): string {
  const list = (DICTS[i18n.lang].colors ?? en.colors) as string[];
  return list[i] ?? String(i);
}

// an option's display name ("layout.chat"); falls back to the raw value
export function opt(prefix: string, v: string | number): string {
  const k = `${prefix}.${v}` as Key;
  const s = t(k);
  return s === k ? String(v) : s;
}
